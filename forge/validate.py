"""Validate the tasks themselves.

A task is only trustworthy if its hidden checks are proven to work. Each task
must pass four conditions:

1. reference passes: the reference solution passes every check, on every run
2. not flaky: every run gives the identical pass/fail vector
3. starter fails: the starter code handed to solvers fails at least one check
4. mutants caught: every planted mutant (a realistic wrong solution) fails
   at least one check

If any condition fails, the task is broken: either it can't be solved, it
accepts wrong answers, or its grade depends on luck.
"""

from __future__ import annotations

import json
from dataclasses import asdict, dataclass, field
from pathlib import Path

from .runner import TASKS_DIR, RunResult, run


@dataclass
class TaskReport:
    task: str
    title: str
    n_checks: int
    reference_passes: bool
    not_flaky: bool
    starter_fails: bool
    starter_failed_checks: list[str]
    mutants: dict[str, list[str]] = field(default_factory=dict)  # mutant -> checks that caught it
    reference_seconds: float = 0.0
    problems: list[str] = field(default_factory=list)

    @property
    def mutants_caught(self) -> int:
        return sum(bool(v) for v in self.mutants.values())

    @property
    def valid(self) -> bool:
        return not self.problems


def _caught_by(r: RunResult) -> list[str]:
    if r.status != "ok":
        return [f"<{r.status}>"]
    return r.failed


def list_tasks() -> list[Path]:
    return sorted(p for p in TASKS_DIR.iterdir() if (p / "task.json").exists())


def validate_task(task_dir: Path, runs: int = 3) -> TaskReport:
    meta = json.loads((task_dir / "task.json").read_text(encoding="utf-8"))
    refs = [run(task_dir, task_dir / "reference.py") for _ in range(runs)]
    starter = run(task_dir, task_dir / "starter.py")
    mutants = {m.stem: run(task_dir, m) for m in sorted((task_dir / "mutants").glob("*.py"))}

    rep = TaskReport(
        task=task_dir.name,
        title=meta["title"],
        n_checks=len(refs[0].checks),
        reference_passes=all(r.all_passed for r in refs),
        not_flaky=len({r.pass_vector() for r in refs}) == 1,
        starter_fails=not starter.all_passed,
        starter_failed_checks=_caught_by(starter),
        mutants={name: _caught_by(r) for name, r in mutants.items()},
        reference_seconds=round(max(sum(c["seconds"] for c in r.checks) for r in refs), 3),
    )
    if not rep.reference_passes:
        bad = {c for r in refs for c in r.failed} or {refs[0].status + ": " + refs[0].error}
        rep.problems.append(f"reference fails: {sorted(bad)}")
    if not rep.not_flaky:
        rep.problems.append("pass/fail differs between identical runs")
    if not rep.starter_fails:
        rep.problems.append("starter already passes every check")
    if not mutants:
        rep.problems.append("no mutants")
    for name, caught in rep.mutants.items():
        if not caught:
            rep.problems.append(f"mutant {name} passes every check")
    return rep


def validate_all(runs: int = 3, only: list[str] | None = None, verbose: bool = True) -> list[TaskReport]:
    reports = []
    for task_dir in list_tasks():
        if only and task_dir.name not in only:
            continue
        rep = validate_task(task_dir, runs)
        reports.append(rep)
        if verbose:
            status = "VALID" if rep.valid else "INVALID: " + "; ".join(rep.problems)
            print(f"{rep.task:28s} checks={rep.n_checks:2d}  mutants caught "
                  f"{rep.mutants_caught}/{len(rep.mutants)}  {status}")
    return reports


def render_markdown(reports: list[TaskReport], runs: int) -> str:
    n_mut = sum(len(r.mutants) for r in reports)
    caught = sum(r.mutants_caught for r in reports)
    lines = [
        "# Task validation report",
        "",
        "Generated by `python -m forge validate`. Every task is checked so that its reference "
        f"passes on all {runs} runs with identical results, and its starter code and every "
        "planted mutant fail at least one hidden check.",
        "",
        f"**{sum(r.valid for r in reports)}/{len(reports)} tasks valid · "
        f"{sum(r.n_checks for r in reports)} hidden checks · {caught}/{n_mut} mutants caught · "
        f"{len(reports)}/{len(reports)} starters rejected**"
        if all(r.starter_fails for r in reports) else "",
        "",
        "| Task | Checks | Reference passes | Stable across runs | Starter rejected | Mutants caught |",
        "|---|---|---|---|---|---|",
    ]
    yes = {True: "yes", False: "**NO**"}
    for r in reports:
        lines.append(f"| {r.title} | {r.n_checks} | {yes[r.reference_passes]} | {yes[r.not_flaky]} | "
                     f"{yes[r.starter_fails]} | {r.mutants_caught}/{len(r.mutants)} |")
    lines += ["", "## Which check caught each planted mutant", ""]
    for r in reports:
        lines.append(f"**{r.title}**")
        lines.append("")
        lines.append(f"- *starter*: {', '.join(r.starter_failed_checks) or 'NOT CAUGHT'}")
        for name, caught in r.mutants.items():
            lines.append(f"- `{name}`: {', '.join(caught) or 'NOT CAUGHT'}")
        lines.append("")
    return "\n".join(lines)


def write_reports(reports: list[TaskReport], runs: int, out_md: Path, out_json: Path) -> None:
    out_md.write_text(render_markdown(reports, runs), encoding="utf-8")
    out_json.write_text(json.dumps([{**asdict(r), "valid": r.valid} for r in reports], indent=2),
                        encoding="utf-8")
